  it("should generate and verify valid ZIP archive binary structure (PK 0x04034b50 signature)", () => {
    // Construct a minimal valid client-side ZIP buffer
    const createTestZipBuffer = (fileName: string, fileContent: string): Uint8Array => {
      const contentBytes = new TextEncoder().encode(fileContent);
      const nameBytes = new TextEncoder().encode(fileName);

      // Local file header (30 bytes + name + content)
      const headerLen = 30 + nameBytes.length;
      const dataLen = contentBytes.length;
      const cdLen = 46 + nameBytes.length;
      const eocdLen = 22;

      const totalSize = headerLen + dataLen + cdLen + eocdLen;
      const buf = new Uint8Array(totalSize);
      const view = new DataView(buf.buffer);

      // 1. Local File Header
      view.setUint32(0, 0x04034b50, true); // PK\x03\x04 signature
      view.setUint16(4, 10, true);         // version needed
      view.setUint16(6, 0, true);          // flags
      view.setUint16(8, 0, true);          // compression (store = 0)
      view.setUint16(10, 0, true);         // time
      view.setUint16(12, 0, true);         // date
      view.setUint32(14, 0, true);         // crc-32 (0 for test)
      view.setUint32(18, dataLen, true);   // compressed size
      view.setUint32(22, dataLen, true);   // uncompressed size
      view.setUint16(26, nameBytes.length, true); // file name length
      view.setUint16(28, 0, true);         // extra field length

      buf.set(nameBytes, 30);
      buf.set(contentBytes, 30 + nameBytes.length);

      // 2. Central Directory Header
      const cdOffset = headerLen + dataLen;
      view.setUint32(cdOffset, 0x02014b50, true); // PK\x01\x02 signature
      view.setUint16(cdOffset + 4, 10, true);
      view.setUint16(cdOffset + 6, 10, true);
      view.setUint16(cdOffset + 8, 0, true);
      view.setUint16(cdOffset + 10, 0, true);
      view.setUint16(cdOffset + 12, 0, true);
      view.setUint16(cdOffset + 14, 0, true);
      view.setUint32(cdOffset + 16, 0, true);
      view.setUint32(cdOffset + 20, dataLen, true);
      view.setUint32(cdOffset + 24, dataLen, true);
      view.setUint16(cdOffset + 28, nameBytes.length, true);
      view.setUint16(cdOffset + 30, 0, true);
      view.setUint16(cdOffset + 32, 0, true);
      view.setUint16(cdOffset + 34, 0, true);
      view.setUint16(cdOffset + 36, 0, true);
      view.setUint32(cdOffset + 38, 0, true);
      view.setUint32(cdOffset + 42, 0, true); // relative offset of local header
      buf.set(nameBytes, cdOffset + 46);

      // 3. End of Central Directory Record (EOCD)
      const eocdOffset = cdOffset + cdLen;
      view.setUint32(eocdOffset, 0x06054b50, true); // PK\x05\x06 signature
      view.setUint16(eocdOffset + 4, 0, true);
      view.setUint16(eocdOffset + 6, 0, true);
      view.setUint16(eocdOffset + 8, 1, true);      // entries this disk
      view.setUint16(eocdOffset + 10, 1, true);     // total entries
      view.setUint32(eocdOffset + 12, cdLen, true); // size of central directory
      view.setUint32(eocdOffset + 16, cdOffset, true); // offset of central directory
      view.setUint16(eocdOffset + 20, 0, true);     // comment length

      return buf;
    };

    const zipBuffer = createTestZipBuffer("README.md", "# CampusOS Portfolio Project\nVerified code submission.");
    const view = new DataView(zipBuffer.buffer);

    // Verify PK\x03\x04 magic number
    expect(view.getUint32(0, true)).toBe(0x04034b50);
    // Verify non-zero size
    expect(zipBuffer.length).toBeGreaterThan(50);
  });

